"""
Конфигурация бота. Все параметры менять здесь.
Секреты берутся из переменных окружения (никогда не хранить в коде!).
"""

import os
from dataclasses import dataclass


@dataclass
class Config:
    # ── Аутентификация ──────────────────────────────────────────────────────
    TOKEN: str = os.environ.get("TINKOFF_TOKEN", "")         # Sandbox или боевой токен
    ACCOUNT_ID: str = os.environ.get("TINKOFF_ACCOUNT_ID", "")

    # ── Инструмент ──────────────────────────────────────────────────────────
    # SBER (Сбербанк обыкновенные акции)
    FIGI: str = "BBG004730N88"
    TICKER: str = "SBER"

    # ── Параметры стратегии ─────────────────────────────────────────────────
    EMA_FAST: int = 9         # Период быстрой EMA
    EMA_SLOW: int = 21        # Период медленной EMA
    VOL_WINDOW: int = 20      # Окно для расчёта среднего объёма

    # ── Риск-менеджмент ─────────────────────────────────────────────────────
    TAKE_PROFIT_PCT: float = 0.30    # Take Profit  0.30%
    STOP_LOSS_PCT: float = 0.15      # Stop Loss    0.15%

    # Размер позиции — фиксированное кол-во лотов (1 лот SBER = 10 акций)
    LOT_SIZE: int = 1                # Лотов на сделку
    MAX_TRADES_PER_DAY: int = 20     # Максимум сделок в день

    # Максимальный дневной убыток (в рублях). Достижение → стоп торговля.
    MAX_DAILY_LOSS: float = 500.0

    # ── Режим ───────────────────────────────────────────────────────────────
    SANDBOX: bool = os.environ.get("SANDBOX", "true").lower() == "true"
